-- job-040: 가입하지 않은 보호자의 아이도 원생으로 등록하고, 그 보호자에게 알림톡을 보낸다.
--
-- 왜 필요한가: 이 서비스의 경쟁 상대는 카톡 단톡방이다. 단톡방은 설치도 가입도 요구하지
-- 않는다. 그런데 pets.userId 가 NOT NULL 이면 "가입한 보호자의 아이만 원생이 될 수 있다"가
-- 되어, 매장이 도입하는 첫날 원생 20마리의 보호자를 전원 가입시켜야 시작이 가능해진다.
-- 실제로는 그 반대여야 한다 — 매장이 전화번호만으로 등록해서 알림톡을 보내기 시작하고,
-- 그 알림톡이 보호자의 가입 유인이 된다.
--
-- 알림톡은 서비스 계정이 아니라 **전화번호**로 발송되므로(수신자는 카카오톡만 있으면 된다)
-- 계정 없이도 발송 자체는 원래 가능했다. 막고 있던 것은 이 두 개의 NOT NULL FK 뿐이다.
--
-- 백필이 필요 없다: NOT NULL -> NULL 완화라 기존 로우는 전부 유효한 상태 그대로 남는다.
-- 반대로 이 마이그레이션은 되돌릴 수 없다(되돌리려면 userId 가 NULL 인 로우를 어떻게 할지
-- 정해야 한다). 롤백 계획은 "이 마이그레이션 이전 시점으로 복원"이 아니라 앞으로 감는 것이다.

-- ── 1. 아직 계정이 연결되지 않은 원생 ────────────────────────────────────────
-- null = 매장이 전화번호(guardian_phone)만 받아 등록한 아이. 보호자가 나중에 같은 번호로
-- 가입하면 InvitationService.claimForUser 가 이 칸을 채운다.
ALTER TABLE "pets" ALTER COLUMN "userId" DROP NOT NULL;

-- ── 2. 미가입 보호자에게 나간 발송 기록 ──────────────────────────────────────
-- 실제 수신처는 언제나 recipient_phone 이고 user_id 는 부가 정보다. 계정이 없다는 이유로
-- 발송 로그를 남기지 못하면, 정작 "보냈는데 안 왔다"는 분쟁에서 근거가 사라진다.
ALTER TABLE "notification_logs" ALTER COLUMN "user_id" DROP NOT NULL;

-- ── 3. 미연결 원생 조회 인덱스 ───────────────────────────────────────────────
-- "우리 매장에서 아직 계정이 연결되지 않은 아이" 는 원장에게 상시 노출되는 목록이고
-- (가입 유도 대상), 전화번호로 회원을 찾는 intake 경로도 이 조합으로 조회한다.
CREATE INDEX "pets_tenant_id_userId_idx" ON "pets"("tenant_id", "userId");
