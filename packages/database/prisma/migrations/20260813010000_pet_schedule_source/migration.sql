-- job-060: 등원 예약 — pet_schedules 행이 누가 넣은 것인지 구분한다.
--
-- 보호자 예약을 별도 테이블로 만들지 않았다. 담는 사실이 "이 아이가 이 날 온다"로
-- 원장이 짠 등원일과 완전히 같기 때문이다. 나누면 그 사실을 읽는 네 곳(오늘의 출석부
-- 자동 생성 · 피드 커버리지 · 태그 후보 · 내일 등원 알림)이 전부 두 테이블을 합쳐
-- 읽어야 하고, 한 곳만 빠뜨리면 "예약은 됐는데 출석부에 안 뜨는" 상태가 된다.
--
-- 대신 출처를 남긴다. 두 가지에 쓰인다:
--
--   1. 삭제 권한 — 보호자는 자기가 잡은 예약만 취소할 수 있다. 원장이 짜 넣은 등원일을
--      보호자가 지우면 매장 운영 계획이 말없이 바뀐다.
--   2. scheduledOn 판정 — 원장의 날짜는 scheduleType = MONTHLY 일 때만 유효하지만,
--      보호자 예약은 그 아이가 WEEKLY 든 MONTHLY 든 언제나 유효하다. 이 칸이 없으면
--      WEEKLY 아이의 예약을 살리려다, MONTHLY -> WEEKLY 로 방식을 바꾼 아이에게 남아
--      있던 옛 행까지 함께 되살아난다(그 아이는 오지 않는데 출석부에 뜬다).
--
-- 기존 행은 전부 원장이 넣은 것이므로 DEFAULT 'ADMIN' 이 곧 정확한 백필이다.
ALTER TABLE "pet_schedules" ADD COLUMN "source" TEXT NOT NULL DEFAULT 'ADMIN';
