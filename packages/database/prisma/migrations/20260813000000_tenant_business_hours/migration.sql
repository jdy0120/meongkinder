-- job-060: 매장 운영시간.
--
-- 모양은 packages/shared 의 BusinessHours 계약이 정한다 — 요일 7개(휴무/개점/마감/휴게
-- 시간) + 공휴일 휴무 + 안내 문구.
--
-- 관계 테이블이 아니라 JSONB 인 이유: 운영시간은 언제나 7일을 통째로 읽고 쓰는 값
-- 객체다. "수요일만 부분 갱신"이 없으므로 테이블로 쪼개면 저장할 때마다 7행
-- delete+insert 를 하고, 그 모델을 Prisma Extension 의 스코프 대상과 RLS 정책에 따로
-- 등록해야 하는데 그 대가로 얻는 게 없다. tenants 의 칸으로 두면 테넌트 격리를 그대로
-- 물려받는다.
--
-- ⚠️ NULL 은 "등록하지 않았다"이며 "매일 휴무"가 아니다. 기존 매장은 전부 NULL 로
-- 시작하고, 화면은 이 상태를 "운영시간 미등록"이라고 말해야 한다 — 기본값을 채워
-- 넣으면 매장이 말한 적 없는 시간을 우리가 지어내 보호자에게 보여주게 된다.
ALTER TABLE "tenants" ADD COLUMN "business_hours" JSONB;
